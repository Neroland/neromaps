#!/usr/bin/env python3
"""write_asset_index.py OUT.md -- writes the asset index (every file, size, purpose, atlas and sheet coordinates)
from tools/art/out/*.json. Run after the three generators."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out")


def main():
    art = json.load(open(os.path.join(OUT, "art_index.json"), encoding="utf-8"))
    man = json.load(open(os.path.join(OUT, "map_icons.json"), encoding="utf-8"))
    snd = json.load(open(os.path.join(OUT, "sound_table.json"), encoding="utf-8"))
    L = []
    w = L.append
    w("# NeroMaps 0.1.0 - asset index\n")
    w("Generated by `tools/art/write_asset_index.py`; do not edit by hand. Paths are relative to "
      "`common/src/main/resources/`. All coordinates are pixels, `u, v, w, h` from the top-left.\n")
    w("Regenerate everything: `python3 tools/art/gen_map_icons.py && python3 tools/art/gen_map_art.py && "
      "python3 tools/art/gen_map_sounds.py` (Pillow, numpy, ffmpeg with libvorbis). Each has `--check`.\n")
    w("## 1. Icon atlas `assets/neromaps/textures/gui/map_icons.png` (256x256)\n")
    w("- 16 px cell of slot *i*: `u = (i % 16) * 16`, `v = (i / 16) * 16`; the art is 14x14 at +1,+1; anchor (hot spot) = cell centre 8,8.")
    w("- 8 px micro cell of slot *i*: `u = (i % 32) * 8`, `v = 192 + (i / 32) * 8`; the art is 7x7 at +0,+0; anchor = pixel 3,3.")
    w("- Draw with nearest filtering. Tint = vertex colour multiply (white body takes the colour, dark outline stays dark).")
    w("- *Inverted* carriers (ring, dashed ring, area) have a dark core and a light glyph; same tint rule.")
    w("- `halo_<carrier>`: 16 px = 1 px ring outside the silhouette (draw under or over the icon, tinted MAP_ACCENT_BRIGHT); "
      "8 px = the carrier's outline pixels (draw over the micro icon).")
    w("- Badges (`badge_*`): 7x7 at the cell origin (16 px) and 5x5 at the cell origin (micro); draw at the marker's top-right corner.")
    w("- War-zone side badges (`badge_side_a` / `_b` / `_none`, slots 131-133): same size and placement as the standing badges; "
      "the side is carried by plate shape and glyph (diamond + I, square + II, round + O), never by colour alone.")
    w("- Radar blips and `trail_marker` are micro-first; their 16 px cell is the legend version.")
    w("- Machine-readable copy: `tools/art/out/map_icons.json` (ship it as `assets/neromaps/map/map_icons.json`).")
    w("- `layer` = no means 0.1.0 does not ship that layer; the icon is drawn so a later release needs no atlas change.\n")
    w("| Icon id | Slot | Carrier | Glyph | Default colour | 16 px u,v,w,h | 8 px u,v,w,h | Layer |")
    w("|---|---|---|---|---|---|---|---|")
    for iid, e in man["icons"].items():
        w(f"| `{iid}` | {e['slot']} | {e['carrier']} | {e['glyph'] or '-'} | {e['colour_name']} `{e['colour']}` | "
          f"{', '.join(map(str, e['uv']))} | {', '.join(map(str, e['micro_uv']))} | {'yes' if e['shipped_layer'] else 'no'} |")
    w("")
    w("Free slots: 30-31, 48-63, 69-71, 73-79, 83-87, 92-95, 100-103, 105-111, 113-119, 122-127, 134-135, 139-143, 146-151, 155-159, 161-191.\n")
    titles = {"map_widgets": "assets/neromaps/textures/gui/map_widgets.png (256x256)",
              "cartography_desk": "assets/neromaps/textures/gui/cartography_desk.png (256x256)",
              "atlas_frame": "assets/neromaps/textures/gui/atlas_frame.png (256x256)",
              "readout_glyphs": "assets/neromaps/textures/gui/minimap/readout_glyphs.png (64x8)"}
    w("## 2. GUI sheets\n")
    w("`border` = nine-slice border in pixels (stretch or tile the middle). Icons on these sheets are white; tint at draw time.\n")
    for sheet, entries in art["sheets"].items():
        w(f"### `{titles.get(sheet, sheet)}`\n")
        w("| Sprite | u,v,w,h | Border | Note |")
        w("|---|---|---|---|")
        for name, e in entries.items():
            w(f"| `{name}` | {', '.join(map(str, e['uv']))} | {e.get('border', '-')} | {e.get('note', '')} |")
        w("")
    w("## 3. Every generated file\n")
    w("| Path | Size | Purpose |")
    w("|---|---|---|")
    w("| `assets/neromaps/textures/gui/map_icons.png` | 256x256 | Marker / layer icon atlas (section 1) |")
    for f in art["files"]:
        size = f"{f['size'][0]}x{f['size'][1]}" if f["size"] else "json"
        w(f"| `{f['path']}` | {size} | {f['purpose']} |")
    w("| `assets/neromaps/sounds.json` | json | 21 sound events with subtitle keys |")
    for k, v in snd.items():
        w(f"| `assets/neromaps/sounds/{k.replace('.', '/')}.ogg` | {v['seconds']} s | `{k}`: {v['recipe']} |")
    w("")
    w("## 4. Sounds\n")
    w("Mono, 32 kHz, Ogg Vorbis q4. Event id = `neromaps:<key>`; subtitle key = `subtitles.neromaps.<key>`.\n")
    w("| Key | Subtitle | Length | Peak | Recipe | Notes |")
    w("|---|---|---|---|---|---|")
    for k, v in snd.items():
        note = "loop; attenuation_distance 6; play at volume <= 0.5" if v.get("loop") else ""
        if k == "ui.zoom":
            note = "pitch 0.8 (far) to 1.25 (near) by zoom step"
        w(f"| `{k}` | {v['subtitle']} | {v['seconds']} s | {v['peak_db']} dBFS | {v['recipe']} | {note} |")
    w("")
    w("## 5. Model wiring notes\n")
    for line in [
        "All block models face **north** (front = north face); rotate in the blockstate.",
        "`render_type: minecraft:cutout` is set on every model with a glow layer (read by Forge/NeoForge; on Fabric register the "
        "cutout layer in the client initialiser).",
        "Glow elements carry `shade: false` and `light_emission: 15` (honoured from 1.21.2; older lines ignore the key and draw them "
        "unshaded but world-lit - acceptable, or give them a full-bright render type).",
        "`cartography_desk`: the plotting slab is rotated -22.5 degrees about x; `cartography_desk_top_glow` is the emissive overlay.",
        "`wall_map[_<mask>][_lit]`: mask bits say which neighbours continue the panel as seen from the front: 1 up, 2 right, 4 down, "
        "8 left (`wall_map` = mask 0, a single panel). `_lit` exists for the eight masks without bits 2 and 4 (the piece that owns the "
        "lower-right corner). The BER draws the map over the glass, inset 2 px on framed sides and 0 px on connected sides, 0.02 in front.",
        "`signpost_post` plus one of `signpost_plate_{1,2,3}` (cardinal) or `signpost_plate_{1,2,3}_diag` (45 degrees) as a multipart. "
        "Plate rows: y 11-15, 6-10, 1-5. Label strip on the plate's north face: x 5-13 of the plate (8 px wide, 2 px high at 1/16 scale); "
        "draw text at 1/4 scale. `tintindex 0` on the glow layer = the icon tile colour.",
        "`trail_marker` / `trail_marker_wall` (wall version is attached to the south side, pointing north): `tintindex 0` = cap colour, "
        "one of the seven marker colours.",
        "`map_table`: relief BER origin is the table top at y = 11/16; keep the hologram inside x/z 1-15, height up to 12/16 above the top.",
        "Items: `waypoint_compass_00..15` (frame 0 = needle up, clockwise 22.5 degrees a frame) and `waypoint_compass_locked_00..15`; "
        "`atlas` (layer1 = clasp glow), `atlas_blank`, `atlas_upgrade_pages`, `atlas_upgrade_binding`, `survey_kit` (layer1 = lens glow), "
        "`signpost`, `trail_marker`, `wall_map` (flat icons), `cartography_desk`, `map_table` (inherit the block model).",
    ]:
        w("- " + line)
    w("")
    with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(L))
    print("wrote", sys.argv[1], len(L), "lines")


if __name__ == "__main__":
    main()
